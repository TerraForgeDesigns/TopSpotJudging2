// Make/Model selector — mirrors
// ui/components/vehicle_selector_list.cpp + ui/screens/
// make_selector_screen.cpp + model_selector_screen.cpp exactly: an
// INLINE keyboard (not a popup overlay — refilters on every keystroke,
// task item 3's "on-screen path is the default" applies here too),
// Recently Used shown only while the search box is empty, Other/Enter
// Manually always present and pre-filled with whatever was typed
// (task's "never type the same thing twice"), bounded results (40) with
// a "keep typing" hint past that. Data comes from
// static/simulator/data/vehicle_data.json — generated by
// firmware/tools/export_vehicle_data_for_simulator.py from the SAME
// source the real device flashes (see that script's own header comment
// for why: HB5 doesn't exist yet, this is the real master list, not a
// second invented one).
import { textKeyboardOverlay } from "./keyboard.js";

const MAX_ROWS = 40;
const MODEL_SEARCH_THRESHOLD = 20; // task item 5: "fewer than about 20 models: show them with no search box"

let vehicleData = null;

async function loadVehicleData() {
  if (vehicleData) return vehicleData;
  const resp = await fetch("/static/simulator/data/vehicle_data.json");
  vehicleData = await resp.json();
  return vehicleData;
}

function containsCI(haystack, needle) {
  if (!needle) return true;
  return haystack.toLowerCase().includes(needle.toLowerCase());
}

export async function findMakes(query) {
  const data = await loadVehicleData();
  const matched = data.filter((m) => containsCI(m.make, query));
  return { matches: matched.slice(0, MAX_ROWS).map((m) => m.make), total: matched.length };
}

export async function findModels(make, query) {
  const data = await loadVehicleData();
  const entry = data.find((m) => m.make.toLowerCase() === (make || "").toLowerCase());
  const models = entry ? entry.models : [];
  const matched = models.filter((m) => containsCI(m, query));
  return { matches: matched.slice(0, MAX_ROWS), total: matched.length };
}

export async function modelBelongsToMake(make, model) {
  const data = await loadVehicleData();
  const entry = data.find((m) => m.make.toLowerCase() === (make || "").toLowerCase());
  if (!entry) return false;
  return entry.models.some((m) => m.toLowerCase() === (model || "").toLowerCase());
}

const TEXT_ROWS = [
  ["q", "w", "e", "r", "t", "y", "u", "i", "o", "p"],
  ["a", "s", "d", "f", "g", "h", "j", "k", "l"],
  ["z", "x", "c", "v", "b", "n", "m"],
];

// Builds the selector UI into `content`. `queryFn(query) -> {matches,
// total}`, `recentsFn() -> string[] | null` (null = no Recently Used
// section at all), `showSearchBox` toggles the search box + inline
// keyboard (Model selector hides both under the 20-model threshold).
// Resolves with { name, manuallyEntered } when a choice is made; never
// resolves if the screen is torn down first (the caller's own
// navigation handles that case).
export function buildVehicleSelector(content, { showSearchBox, searchPlaceholder, manualPlaceholder, queryFn, recentsFn }) {
  return new Promise((resolve) => {
    let query = "";
    const wrap = document.createElement("div");
    wrap.style.display = "flex";
    wrap.style.flexDirection = "column";
    wrap.style.height = "100%";
    wrap.style.gap = "8px";

    let searchArea = null;
    if (showSearchBox) {
      searchArea = document.createElement("div");
      searchArea.className = "key-textarea";
      searchArea.style.height = "62px";
      wrap.appendChild(searchArea);
    }

    const listArea = document.createElement("div");
    listArea.style.flex = "1";
    listArea.style.overflowY = "auto";
    listArea.style.display = "flex";
    listArea.style.flexDirection = "column";
    listArea.style.gap = "6px";
    wrap.appendChild(listArea);

    function addRow(label, onClick) {
      const row = document.createElement("div");
      row.className = "list-row";
      row.textContent = label;
      row.addEventListener("click", onClick);
      listArea.appendChild(row);
      return row;
    }

    async function refilter() {
      listArea.innerHTML = "";

      if (!query && recentsFn) {
        const recents = recentsFn();
        if (recents && recents.length > 0) {
          const header = document.createElement("div");
          header.className = "text-secondary";
          header.style.fontFamily = "'IBM Plex Sans', sans-serif";
          header.style.fontWeight = "600";
          header.style.fontSize = "18px";
          header.textContent = "Recently Used";
          listArea.appendChild(header);
          for (const name of recents) {
            addRow(name, () => resolve({ name, manuallyEntered: false }));
          }
        }
      }

      addRow("Other / Enter Manually", async () => {
        const result = await textKeyboardOverlay(query, manualPlaceholder, 47);
        if (result.accepted && result.text) resolve({ name: result.text, manuallyEntered: true });
        // Cancel: selector screen just stays put, matching the firmware's own rule.
      });

      const { matches, total } = await queryFn(query);
      for (const name of matches) {
        addRow(name, () => resolve({ name, manuallyEntered: false }));
      }
      if (total > matches.length) {
        const hint = document.createElement("div");
        hint.className = "text-secondary";
        hint.style.fontSize = "13px";
        hint.textContent = `${total - matches.length} more - keep typing to narrow it down`;
        listArea.appendChild(hint);
      }
    }

    if (showSearchBox) {
      const kb = document.createElement("div");
      kb.className = "keyboard-grid";
      kb.style.height = "220px";
      kb.style.flexShrink = "0";

      function renderSearch() {
        searchArea.textContent = query || searchPlaceholder || "";
        searchArea.style.color = query ? "" : "var(--text-secondary)";
      }
      function applyKey(key) {
        if (key === "Delete") query = query.slice(0, -1);
        else if (key === "Space") query += " ";
        else query += key;
        renderSearch();
        refilter();
      }
      for (const row of TEXT_ROWS) {
        const rowEl = document.createElement("div");
        rowEl.className = "key-row";
        for (const k of row) {
          const btn = document.createElement("button");
          btn.className = "key";
          btn.textContent = k;
          btn.addEventListener("click", () => applyKey(k));
          rowEl.appendChild(btn);
        }
        kb.appendChild(rowEl);
      }
      const bottomRow = document.createElement("div");
      bottomRow.className = "key-row";
      const spaceBtn = document.createElement("button");
      spaceBtn.className = "key key-wide";
      spaceBtn.textContent = "Space";
      spaceBtn.addEventListener("click", () => applyKey("Space"));
      const deleteBtn = document.createElement("button");
      deleteBtn.className = "key key-wide";
      deleteBtn.textContent = "Delete";
      deleteBtn.addEventListener("click", () => applyKey("Delete"));
      bottomRow.append(spaceBtn, deleteBtn);
      kb.appendChild(bottomRow);

      wrap.appendChild(kb);
      renderSearch();
    }

    content.appendChild(wrap);
    refilter();
  });
}

export { loadVehicleData, MODEL_SEARCH_THRESHOLD };
